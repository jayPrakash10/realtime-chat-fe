// Turns .env (or .env.example as a fallback) into src/environments/environment.ts.
// Shell environment variables override values from the file, which is handy in CI.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';

const sourceFile = existsSync('.env') ? '.env' : '.env.example';
const fromFile = parseEnv(readFileSync(sourceFile, 'utf8'));
const read = (key) => String(process.env[key] ?? fromFile[key] ?? '').trim();
const withoutTrailingSlash = (value) => value.replace(/\/+$/, '');

const config = {
  apiBaseUrl: withoutTrailingSlash(read('NG_APP_API_BASE_URL')),
  serverOrigin: withoutTrailingSlash(read('NG_APP_SERVER_ORIGIN')),
  useMocks: read('NG_APP_USE_MOCKS').toLowerCase() === 'true',
};

for (const [key, value] of [
  ['NG_APP_API_BASE_URL', config.apiBaseUrl],
  ['NG_APP_SERVER_ORIGIN', config.serverOrigin],
]) {
  if (!value) {
    console.error(`[env] ${key} is missing in ${sourceFile}`);
    process.exit(1);
  }
}

// On Vercel the .env.example fallback would point a deployed app at localhost, so require real values.
if (process.env.VERCEL && !config.useMocks) {
  const missing = ['NG_APP_API_BASE_URL', 'NG_APP_SERVER_ORIGIN'].filter((key) => !process.env[key]);
  if (missing.length) {
    console.error(
      `[env] Set ${missing.join(' and ')} in Vercel → Project Settings → Environment Variables, ` +
        'or set NG_APP_USE_MOCKS=true for a demo deployment.',
    );
    process.exit(1);
  }
  for (const [key, value] of [
    ['NG_APP_API_BASE_URL', config.apiBaseUrl],
    ['NG_APP_SERVER_ORIGIN', config.serverOrigin],
  ]) {
    if (value.startsWith('http://')) {
      console.warn(`[env] ${key} uses http://. Browsers block it from an https:// Vercel page (mixed content).`);
    }
  }
}

mkdirSync('src/environments', { recursive: true });
writeFileSync(
  'src/environments/environment.ts',
  `// Generated by scripts/generate-env.mjs from ${sourceFile}. Do not edit: change .env instead.\n` +
    `export const environment = {\n` +
    `  apiBaseUrl: ${JSON.stringify(config.apiBaseUrl)},\n` +
    `  serverOrigin: ${JSON.stringify(config.serverOrigin)},\n` +
    `  useMocks: ${config.useMocks},\n` +
    `} as const;\n`,
);
console.log(`[env] src/environments/environment.ts written from ${sourceFile} (mocks: ${config.useMocks})`);
